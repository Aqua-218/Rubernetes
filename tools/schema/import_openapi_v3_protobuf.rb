# frozen_string_literal: true

require "digest"

# Import the gnostic wire layout from the Kubernetes v1.36.2 vendor tree.
upstream = ARGV.fetch(0) { abort "usage: ruby tools/schema/import_openapi_v3_protobuf.rb KUBERNETES_SOURCE" }
path = "vendor/github.com/google/gnostic-models/openapiv3/OpenAPIv3.proto"
source = File.binread(File.join(upstream, path))
digest = Digest::SHA256.hexdigest(source)
abort "gnostic OpenAPI v3 source does not match Kubernetes v1.36.2" unless digest == "86020d80ec36cd3d57b9aa0c869e78ea837513c75131b8e0a01a757aefbac66a"
messages = source.scan(/^message (\w+) \{\n(.*?)^\}/m)
abort "gnostic OpenAPI v3 Document was not found" unless messages.any? { |name, _| name == "Document" }

target = File.expand_path("../../lib/rubernetes/api/openapi_v3_protobuf_schema.rb", __dir__)
File.open(target, "w") do |file|
  file.puts <<~HEADER
    # frozen_string_literal: true

    # Generated by tools/schema/import_openapi_v3_protobuf.rb from Kubernetes v1.36.2.
    # #{path}
    # SHA-256 #{digest}
    module Rubernetes
      module API
        module OpenAPIV3ProtobufSchema
          MESSAGES = {
  HEADER
  messages.each_with_index do |(name, body), message_index|
    fields = body.scan(/^\s*(?:(repeated) )?([\w.]+) (\w+) = (\d+);$/)
    file.puts %(        #{name.inspect} => [)
    fields.each_with_index do |(repeated, type, key, number), field_index|
      json_key = key == "_ref" ? "$ref" : key.gsub(/_([a-z])/) { Regexp.last_match(1).upcase }
      comma = "," if field_index + 1 < fields.size
      file.puts %(          [#{number}, #{json_key.inspect}, #{type.inspect}#{", true" if repeated}].freeze#{comma})
    end
    file.puts "        ].freeze#{"," if message_index + 1 < messages.size}"
  end
  file.puts <<~FOOTER
          }.freeze
        end
      end
    end
  FOOTER
end
