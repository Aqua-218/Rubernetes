# frozen_string_literal: true

require "tempfile"
require_relative "../../lib/rubernetes/manifest"

# RBS discovers a gem's signatures under sig/. Ask the actual manifest builder
# for its installed methods so aliases and version-qualified names stay in sync.
module ManifestSignatures
  ROOT = File.expand_path("../..", __dir__)
  OUTPUT = File.join(ROOT, "sig/rubernetes/manifest_resources.rbs")

  Manifest = Rubernetes::Manifest

  # Use the same preferred-version and qualified-name resolution as render.
  class ResourceNames < Manifest::Builder
    def resource(api_version:, kind:, **) = [api_version, kind]
  end

  class Generator
    ROOT_HELPERS = {
      Manifest::Workload::PodTemplate => "_PodTemplateDSL",
      Manifest::Workload::ClaimTemplates => "_ClaimTemplateDSL",
      Manifest::ConfigRollout => "_RolloutDSL"
    }.freeze

    def initialize(registry, definitions)
      @builder = ResourceNames.new(registry: registry, definitions: definitions)
      @schema = Manifest::Schema.new(definitions)
      short_names = definitions.keys.map { |key| key.split(".").last }.tally
      @type_names = {}
      @targets = {}
      registry.fetch("types").each do |type|
        key = type.fetch("schema")
        short = key.split(".").last
        @type_names[key] = short_names.fetch(short) == 1 ? short : type.fetch("ruby_constant")
        type.fetch("gvks").each do |gvk|
          api_version = [gvk.fetch("group"), gvk.fetch("version")].reject(&:empty?).join("/")
          @targets[[api_version, gvk.fetch("kind")]] = key
        end
      end
      @fields = {}
      @interfaces = {}
    end

    def render
      field_interface(Manifest::Workload::CONTAINER, "_ContainerSchemaFields", Manifest::Workload::ContainerFields.public_instance_methods)
      field_interface(Manifest::Workload::POD_SPEC, "_PodSpecSchemaFields", Manifest::PodCredentialFields.public_instance_methods)
      declarations = @builder.singleton_methods.sort.map do |name|
        api_version, kind = @builder.public_send(name, "example")
        receiver = root_receiver(api_version, kind)
        "      def #{name}: (resource_name name, ?namespace: resource_name?, **untyped metadata) ?{ () [self: #{receiver}] -> void } -> resource"
      end
      [
        "# Generated by rake rbs:generate from the manifest registry.",
        "module Rubernetes", "  module Manifest",
        *@interfaces.sort.map(&:last), "    class Builder",
        *declarations, "    end", "  end", "end", ""
      ].join("\n")
    end

    private

    def root_receiver(api_version, kind)
      type = @targets.fetch([api_version, kind])
      object = {"apiVersion" => api_version, "kind" => kind}
      context = Manifest::ObjectBuilder.new(object: object, schema_name: type, schema: @schema)
      Manifest::Workload.install(context, object, type, @schema)
      helpers = ROOT_HELPERS.select { |mod, _signature| context.is_a?(mod) }
      overridden = helpers.keys.flat_map(&:public_instance_methods) & fields_for(type).keys
      fields = if overridden.empty?
                 schema_interface(type)
               else
                 field_interface(type, "_#{@type_names.fetch(type)}DeclarationFields", overridden)
               end
      receiver = ["ObjectBuilder", fields, *helpers.values]
      receiver << "_RawImagePullSecretsDSL" if context.is_a?(Manifest::PodCredentialFields) && context.method(:image_pull_secrets).super_method
      receiver.compact.join(" & ")
    end

    def schema_interface(type)
      field_interface(type, "_#{@type_names.fetch(type)}Fields", []) unless fields_for(type).empty?
    end

    def field_interface(type, name, overridden)
      return name if @interfaces.key?(name)

      @interfaces[name] = nil # A nested object can refer back to this type.
      fields = fields_for(type)
      methods = fields.except(*overridden).sort.map do |field, schema|
        "      def #{field}: #{field_signature(schema)}"
      end
      # A schema setter named secret takes precedence over the reference helper.
      references = %i[configmap secret] - fields.keys
      if references.size == 2
        methods.unshift("      include _ResourceReferenceDSL")
      else
        references.each { |helper| methods << "      def #{helper}: (resource_name name) -> Reference" }
      end
      @interfaces[name] = ["    interface #{name}", *methods, "    end", ""].join("\n")
      name
    end

    def fields_for(type)
      @fields[type] ||= begin
        definition = @schema.definition(type).fetch("properties", {})
        spec = @schema.reference(definition.fetch("spec", {}))
        shortcuts = spec ? @schema.definition(spec).fetch("properties", {}) : {}
        # Direct fields win over spec shortcuts on ObjectBuilder.
        shortcuts.merge(definition).each_with_object({}) do |(json_name, schema), fields|
          name = Manifest::Schema.underscore(json_name)
          fields[name.to_sym] = schema unless Manifest::ObjectBuilder::RESERVED_METHODS.include?(name)
        end
      end
    end

    def field_signature(schema)
      reference = @schema.reference(schema)
      if reference
        receiver = schema_interface(reference) || "_ResourceReferenceDSL"
        value = @schema.definition(reference)["properties"] ? "Hash[untyped, untyped]?" : "untyped"
        return ["(#{value} value) -> untyped", "(**untyped fields) -> untyped",
                "() { () [self: ObjectBuilder & #{receiver}] -> void } -> resource"].join("\n           | ")
      end
      case schema["type"]
      when "object" then "(Hash[untyped, untyped]? value) -> untyped\n           | (**untyped fields) -> untyped"
      when "array" then "(Array[untyped]? value) -> untyped"
      when "integer" then "(Integer? value) -> untyped"
      when "number" then "((Integer | Float)? value) -> untyped"
      when "boolean" then "(bool? value) -> untyped"
      when "string"
        value = schema["format"] == "int-or-string" ? "String | Symbol | Integer" : "String | Symbol"
        "((#{value})? value) -> untyped"
      else "(untyped value) -> untyped"
      end
    end
  end

  def self.render
    registry = JSON.parse(File.binread(File.join(ROOT, "generated/schema/registry.json")))
    definitions = JSON.parse(File.binread(File.join(ROOT, "generated/openapi/v2.json"))).fetch("definitions")
    Generator.new(registry, definitions).render
  end
end

if $PROGRAM_NAME == __FILE__
  output = ManifestSignatures::OUTPUT
  signature = ManifestSignatures.render
  case ARGV
  when ["--check"]
    abort "Manifest resource signatures are stale. Run rake rbs:generate." unless File.file?(output) && File.binread(output) == signature
  when []
    Tempfile.create(["manifest_resources", ".rbs"], File.dirname(output)) do |file|
      file.write(signature)
      file.close
      File.chmod(0o644, file.path)
      File.rename(file.path, output)
    end
  else
    abort "Usage: ruby tools/schema/manifest_signatures.rb [--check]"
  end
end
